// Assembles the aligned translation chunks (docs/tr/sNN.{en,ar}.txt) into lazy-loaded dictionary modules.
// Usage: node scripts/build-content-dict.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const keys = JSON.parse(readFileSync('docs/keys-static.json', 'utf8'));
const CHUNK = 200;
const HEB = /[֐-׿]/;
const isGarbage = (k) => /[{}]|\/\/|\n|<|>|=>|className/.test(k) || !HEB.test(k);

// --- sentence patterns with values (docs/tr/tpl.txt: "he ||| en ||| ar", {} = value) ---
{
  const rows = [];
  for (const line of readFileSync('docs/tr/tpl.txt', 'utf8').split('\n')) {
    if (!line.trim() || line.startsWith('#')) continue;
    const [he, en, ar] = line.replace(/\r$/, '').split(' ||| ').map((s) => s.trim());
    if (!he || !en || !ar) { console.warn('bad tpl line:', line.slice(0, 80)); continue; }
    if (HEB.test(en) || HEB.test(ar)) console.warn('Hebrew left in translation:', (HEB.test(en) ? en : ar).slice(0, 80));
    let n = 0;
    rows.push([he.replace(/\{\}/g, () => `{${n++}}`), en, ar]);
  }
  const body = `// GENERATED by scripts/build-content-dict.mjs from docs/tr/tpl.txt — do not edit by hand.\nimport type { Pattern } from './patterns';\nexport const EXTRA_PATTERNS: Pattern[] = ${JSON.stringify(rows)};\n`;
  writeFileSync('src/shared/i18n/patterns.extra.ts', body, 'utf8');
  console.log('patterns', rows.length);
}

for (const lang of ['en', 'ar']) {
  const lines = [];
  for (let c = 0; c * CHUNK < keys.length; c++) {
    const n = String(c).padStart(2, '0');
    const raw = readFileSync(`docs/tr/s${n}.${lang}.txt`, 'utf8').split('\n');
    if (raw[raw.length - 1] === '') raw.pop();
    const expected = Math.min(CHUNK, keys.length - c * CHUNK);
    if (raw.length !== expected) throw new Error(`s${n}.${lang}: ${raw.length} lines, expected ${expected}`);
    lines.push(...raw.map((l) => l.replace(/\r$/, '')));
  }
  const dict = {};
  let skipped = 0;
  keys.forEach((k, i) => {
    const v = lines[i].trim();
    const key = k.trim();
    if (!v || v === '-' || isGarbage(key) || v === key) { skipped++; return; }
    if (!(key in dict)) dict[key] = v;
  });
  // supplementary entries (fragments, labels) – these win over the generated ones
  const extra = ["docs/tr/extra.tsv", "docs/tr/extra2.tsv", "docs/tr/extra3.tsv", "docs/tr/war1.tsv", "docs/tr/laws.tsv", "docs/tr/projects.tsv"].flatMap((f) => readFileSync(f, 'utf8').split('\n')).filter((l) => l.trim());
  for (const line of extra) {
    const [he, en, ar] = line.replace(/\r$/, '').split('\t');
    if (he && en && ar) dict[he.trim()] = (lang === 'en' ? en : ar).trim();
  }
  const body = `// GENERATED by scripts/build-content-dict.mjs from docs/tr — do not edit by hand.\nconst D: Record<string, string> = ${JSON.stringify(dict)};\nexport default D;\n`;
  writeFileSync(`src/shared/i18n/content.${lang}.ts`, body, 'utf8');
  console.log(lang, Object.keys(dict).length, 'entries,', skipped, 'skipped');
}

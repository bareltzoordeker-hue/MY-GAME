// Builds each ministry's own laws and reforms from docs/laws/<ministryId>.tsv.
// Columns (tab-separated):
//   level (L = law, R = reform) | icon | ideology "security,economic,religion" | groups "id:v,id:v" |
//   extra "b=category:amount;s=service:amount" (or empty) | he title | he description |
//   en title | en description | ar title | ar description
// Writes src/data/ministryLaws.generated.ts (Hebrew game data) and docs/tr/laws.tsv (translations).
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';

const GROUPS = new Set(['youth', 'elderly', 'families', 'lowIncome', 'middleClass', 'highIncome', 'soldiers', 'reservists', 'haredim', 'secular', 'religious', 'center', 'periphery', 'settlers', 'left', 'right', 'selfEmployed', 'employees', 'publicSector', 'students', 'retirees', 'arabs', 'liberals', 'socialists', 'olim']);
const CATS = new Set(['defense', 'education', 'health', 'transport', 'welfare', 'housing', 'infrastructure', 'police', 'agriculture', 'energy', 'science', 'culture', 'government']);
const SERVICES = new Set(['health', 'education', 'transport', 'housing', 'security', 'welfare', 'infrastructure', 'energy', 'govServices']);
const DOMAIN = {
  defense: 'defense', finance: 'finance', foreign: 'foreign', justice: 'law', national_security: 'law', interior: 'interior', health: 'health',
  education: 'education', transport: 'transport', economy: 'economy', housing: 'housing', energy: 'energy', welfare: 'welfare', environment: 'energy',
  agriculture: 'agriculture', communications: 'media', culture: 'culture', tourism: 'economy', labor: 'welfare', religious: 'interior', jerusalem: 'interior',
  heritage: 'culture', negev_galilee: 'infrastructure', aliyah: 'interior', science: 'science', regional: 'foreign', settlement: 'interior', diaspora: 'foreign',
  social_equality: 'welfare', intelligence: 'defense', strategic: 'foreign', periphery: 'infrastructure', cyber: 'science', public_diplomacy: 'media', national_resilience: 'welfare',
};
const HEB = /[֐-׿]/;

const errors = [];
const laws = [];
const tr = [];
const seen = new Set();
for (const id of Object.keys(DOMAIN)) {
  let text;
  try { text = readFileSync(`docs/laws/${id}.tsv`, 'utf8'); } catch { errors.push(`${id}: missing docs/laws/${id}.tsv`); continue; }
  const rows = text.split('\n').map((l) => l.replace(/\r$/, '')).filter((l) => l.trim() && !l.startsWith('#'));
  let nL = 0, nR = 0;
  rows.forEach((line, i) => {
    const c = line.split('\t').map((x) => x.trim());
    const where = `${id}.tsv:${i + 1}`;
    if (c.length !== 11) { errors.push(`${where}: ${c.length} columns`); return; }
    const [lv, icon, ideo, groups, extra, heT, heD, enT, enD, arT, arD] = c;
    if (lv !== 'L' && lv !== 'R') errors.push(`${where}: level ${lv}`);
    lv === 'L' ? nL++ : nR++;
    const [sec, eco, rel] = ideo.split(',').map(Number);
    if ([sec, eco, rel].some((x) => !Number.isFinite(x) || Math.abs(x) > 1)) errors.push(`${where}: ideology ${ideo}`);
    const g = {};
    for (const part of groups.split(',').filter(Boolean)) {
      const [k, v] = part.split(':');
      if (!GROUPS.has(k) || !Number.isFinite(Number(v)) || Math.abs(Number(v)) > 15) errors.push(`${where}: group ${part}`);
      g[k] = Number(v);
    }
    const law = {
      id: `${id}__${String(i + 1).padStart(2, '0')}`, title: heT, icon, domain: DOMAIN[id], level: lv === 'R' ? 'major' : 'medium',
      ideology: { security: sec, economic: eco, religion: rel }, description: heD, groups: g, ministries: [id],
    };
    for (const part of extra.split(';').filter((x) => x && x !== '-')) {
      const [k, rest] = part.split('=');
      const [a, b] = rest.split(':');
      if (k === 'b' && CATS.has(a) && Number(b) > 0 && Number(b) <= 5) law.budget = { category: a, amount: Number(b) };
      else if (k === 's' && SERVICES.has(a) && Math.abs(Number(b)) <= 5) law.serviceBonus = { ...law.serviceBonus, [a]: Number(b) };
      else errors.push(`${where}: extra ${part}`);
    }
    if (!heT || !heD || !HEB.test(heT)) errors.push(`${where}: Hebrew text`);
    if ([enT, enD, arT, arD].some((x) => !x || HEB.test(x))) errors.push(`${where}: translation missing or has Hebrew`);
    if (seen.has(heT)) errors.push(`${where}: duplicate title ${heT}`);
    seen.add(heT);
    laws.push(law);
    tr.push(`${heT}\t${enT}\t${arT}`, `${heD}\t${enD}\t${arD}`);
  });
  if (nL < 15 || nR < 15) errors.push(`${id}: ${nL} laws and ${nR} reforms (need 15 + 15)`);
}
if (errors.length) { console.error(errors.join('\n')); process.exit(1); }
writeFileSync('src/data/ministryLaws.generated.ts',
  `// GENERATED by scripts/build-ministry-laws.mjs from docs/laws — do not edit by hand.\nimport type { LawDef } from './laws';\nexport const MINISTRY_LAWS: LawDef[] = ${JSON.stringify(laws)} as LawDef[];\n`, 'utf8');
writeFileSync('docs/tr/laws.tsv', tr.join('\n') + '\n', 'utf8');
console.log('ministry laws:', laws.length);

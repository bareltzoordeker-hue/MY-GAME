// Builds each ministry's own national projects from docs/projects/<ministryId>.tsv.
// Columns (tab-separated): icon | service | region | cost (₪B) | turns (2-month steps) | bonus | groups "id:v,id:v" |
//   he name | en name | ar name
// Writes src/data/ministryProjects.generated.ts and docs/tr/projects.tsv.
import { readFileSync, writeFileSync } from 'node:fs';

const GROUPS = new Set(['youth', 'elderly', 'families', 'lowIncome', 'middleClass', 'highIncome', 'soldiers', 'reservists', 'haredim', 'secular', 'religious', 'center', 'periphery', 'settlers', 'left', 'right', 'selfEmployed', 'employees', 'publicSector', 'students', 'retirees', 'arabs', 'liberals', 'socialists', 'olim']);
const SERVICES = new Set(['health', 'education', 'transport', 'housing', 'security', 'welfare', 'infrastructure', 'energy', 'govServices']);
const REGIONS = new Set(['north', 'haifa', 'sharon', 'center', 'jerusalem', 'shfela', 'judea_samaria', 'negev', 'eilat']);
const IDS = ['defense', 'finance', 'foreign', 'justice', 'national_security', 'interior', 'health', 'education', 'transport', 'economy', 'housing', 'energy', 'welfare', 'environment', 'agriculture', 'communications', 'culture', 'tourism', 'labor', 'religious', 'jerusalem', 'heritage', 'negev_galilee', 'aliyah', 'science', 'regional', 'settlement', 'diaspora', 'social_equality', 'intelligence', 'strategic', 'periphery', 'cyber', 'public_diplomacy', 'national_resilience'];
const HEB = /[֐-׿]/;

const errors = [];
const out = [];
const tr = [];
const names = new Set();
for (const id of IDS) {
  let text;
  try { text = readFileSync(`docs/projects/${id}.tsv`, 'utf8'); } catch { errors.push(`${id}: missing docs/projects/${id}.tsv`); continue; }
  const rows = text.split('\n').map((l) => l.replace(/\r$/, '')).filter((l) => l.trim() && !l.startsWith('#'));
  rows.forEach((line, i) => {
    const c = line.split('\t').map((x) => x.trim());
    const where = `${id}.tsv:${i + 1}`;
    if (c.length !== 10) { errors.push(`${where}: ${c.length} columns`); return; }
    const [icon, service, region, cost, turns, bonus, groups, he, en, ar] = c;
    if (!SERVICES.has(service)) errors.push(`${where}: service ${service}`);
    if (!REGIONS.has(region)) errors.push(`${where}: region ${region}`);
    const n = (x, lo, hi) => { const v = Number(x); if (!Number.isFinite(v) || v < lo || v > hi) errors.push(`${where}: number ${x}`); return v; };
    const g = {};
    for (const part of groups.split(',').filter(Boolean)) {
      const [k, v] = part.split(':');
      if (!GROUPS.has(k) || !Number.isFinite(Number(v)) || Math.abs(Number(v)) > 8) errors.push(`${where}: group ${part}`);
      g[k] = Number(v);
    }
    if (!he || !HEB.test(he) || !en || !ar || HEB.test(en) || HEB.test(ar)) errors.push(`${where}: names`);
    if (names.has(he)) errors.push(`${where}: duplicate ${he}`);
    names.add(he);
    out.push({ id: `${id}__p${String(i + 1).padStart(2, '0')}`, name: he, icon, service, region, cost: n(cost, 0.3, 60), turns: n(turns, 2, 36), bonus: n(bonus, 0, 10), groups: g, ministry: id });
    tr.push(`${he}\t${en}\t${ar}`);
  });
  if (rows.length < 15) errors.push(`${id}: ${rows.length} projects (need 15)`);
}
if (errors.length) { console.error(errors.join('\n')); process.exit(1); }
writeFileSync('src/data/ministryProjects.generated.ts', `// GENERATED by scripts/build-ministry-projects.mjs from docs/projects — do not edit by hand.\nimport type { ProjectDef } from './projects';\nexport const MINISTRY_PROJECTS: ProjectDef[] = ${JSON.stringify(out)} as ProjectDef[];\n`, 'utf8');
writeFileSync('docs/tr/projects.tsv', tr.join('\n') + '\n', 'utf8');
console.log('ministry projects:', out.length);

// A woman who speaks about herself in the masculine ("אני מתלבט") breaks the game's voice.
// Politicians' lines are written in the masculine; this turns the first-person forms into feminine for female speakers.
const PAIRS: Record<string, string> = {
  מבקש: 'מבקשת', מעריך: 'מעריכה', צריך: 'צריכה', סומך: 'סומכת', מתנגד: 'מתנגדת', יכול: 'יכולה', תומך: 'תומכת', מוכן: 'מוכנה',
  זוכר: 'זוכרת', נותן: 'נותנת', מרגיש: 'מרגישה', מקבל: 'מקבלת', מציע: 'מציעה', מעדיף: 'מעדיפה', מופתע: 'מופתעת', חושב: 'חושבת',
  בטוח: 'בטוחה', אוהב: 'אוהבת', שוקל: 'שוקלת', שומע: 'שומעת', שוכח: 'שוכחת', רושם: 'רושמת', רגיל: 'רגילה', פתוח: 'פתוחה',
  עוקב: 'עוקבת', נלחם: 'נלחמת', מתרגש: 'מתרגשת', מתלבט: 'מתלבטת', מתכוון: 'מתכוונת', מקשיב: 'מקשיבה', מצליח: 'מצליחה',
  מסתיר: 'מסתירה', מניח: 'מניחה', מזהיר: 'מזהירה', מודיע: 'מודיעה', מבטיח: 'מבטיחה', מאוכזב: 'מאוכזבת', כותב: 'כותבת',
  זמין: 'זמינה', מתחייב: 'מתחייבת', מסכים: 'מסכימה', מתכנן: 'מתכננת', מעוניין: 'מעוניינת', מתעניין: 'מתעניינת', מדבר: 'מדברת',
  מכיר: 'מכירה', מבין: 'מבינה', חושש: 'חוששת', מאמין: 'מאמינה', שמח: 'שמחה', עסוק: 'עסוקה', מחזיק: 'מחזיקה', ממתין: 'ממתינה',
  מתלהב: 'מתלהבת', מחליט: 'מחליטה', מתעקש: 'מתעקשת', נשאר: 'נשארת', עובד: 'עובדת', חוזר: 'חוזרת', מתעדכן: 'מתעדכנת', מרגיז: 'מרגיזה',
  שותף: 'שותפה', מקווה: 'מקווה', מצפה: 'מצפה', רוצה: 'רוצה', מנסה: 'מנסה', מחכה: 'מחכה', רואה: 'רואה',
};
const ADV = String.raw`(?:\s+(?:לא|גם|כבר|עדיין|באמת|ממש|תמיד|עכשיו|רק|מאוד))*`;
const FIRST = new RegExp(String.raw`(?<![א-ת])(ו?אני)(${ADV})\s+([א-ת]+)(?![א-ת])`, 'g');
const STANDALONE = /(?<![א-ת])(שמח|מופתע|מאוכזב)(?![א-ת])(?=\s+(?:לשמוע|לראות|מהתגובה|מההחלטה|מהמהלך|מהדרך|מאוד))/g;

export function feminize(text: string): string {
  return text
    .replace(FIRST, (m, pron: string, adv: string, w: string) => (PAIRS[w] ? `${pron}${adv} ${PAIRS[w]}` : m))
    .replace(STANDALONE, (m, w: string) => PAIRS[w] ?? m);
}
